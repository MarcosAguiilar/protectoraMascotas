CREATE TABLE solicitud_adopcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id BIGINT NOT NULL,
    nombre_solicitante VARCHAR(150) NOT NULL,
    email_solicitante VARCHAR(254) NOT NULL,
    fecha_solicitud TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    CONSTRAINT fk_solicitud_adopcion_mascota FOREIGN KEY (mascota_id) REFERENCES mascota (id),
    CONSTRAINT ck_solicitud_adopcion_estado CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA'))
);

CREATE INDEX idx_solicitud_adopcion_mascota_id ON solicitud_adopcion (mascota_id);
